let num1 = 13;
let num2 = 26;

let remainder1 = num1 % 2;
let remainder2 = num2 % 2;

if (remainder1 == 0) {
    console.log("The number", num1, "is even.")
}
else {
    console.log("The number", num1, "is odd.")
}

if (remainder2 == 0) {
    console.log("The number", num2, "is even.")
}
else {
    console.log("The number", num2, "is odd.")
}